#!/usr/bin/env node
/**
 * Generate `src/lib/brand-icons.ts` from simple-icons (CC0-1.0).
 *
 * The responder page must be self-contained — no webfont, no sprite request — so the
 * brand marks are inlined as path data at build time rather than loaded from anywhere. Generating the file (instead of hand-copying the paths) keeps the shapes
 * exactly as published and makes the provenance reproducible:
 *
 *     pnpm add -D simple-icons && node scripts/make-brand-icons.mjs
 *
 * Trademarks belong to their owners; the marks are used only to label the service each
 * button dials, which is what they are for.
 */
import { writeFileSync } from 'node:fs';
import * as simpleIcons from 'simple-icons';

// Channel marks for the card page, plus the repository mark for the footer's Source link.
const WANTED = ['whatsapp', 'signal', 'telegram', 'viber', 'github'];

const entries = WANTED.map((slug) => {
  const key = Object.keys(simpleIcons).find((name) => name.toLowerCase() === `si${slug}`);
  const icon = key ? simpleIcons[key] : null;
  if (!icon) throw new Error(`simple-icons has no entry for ${slug}`);
  return { slug, title: icon.title, hex: icon.hex, path: icon.path };
});

const body = entries
  .map(
    (icon) => `  ${icon.slug}: {
    title: '${icon.title}',
    hex: '#${icon.hex}',
    path:
      '${icon.path}',
  },`,
  )
  .join('\n');

writeFileSync(
  'src/lib/brand-icons.ts',
  `/**
 * Brand marks for the reachability channels, generated by
 * \`scripts/make-brand-icons.mjs\` from simple-icons (CC0-1.0). Do not edit by hand.
 *
 * The responder page inlines these: a stranger's page must not fetch an icon from
 * anywhere, and a button that dials WhatsApp should look like WhatsApp.
 */
export interface BrandIcon {
  title: string;
  /** The brand's own colour, for the icon inside a labelled button. */
  hex: string;
  /** 24×24 viewBox path data. */
  path: string;
}

export const BRAND_ICONS: Record<string, BrandIcon> = {
${body}
};

export function brandIcon(slug: string): BrandIcon | undefined {
  return BRAND_ICONS[slug];
}
`,
);
console.log(`wrote src/lib/brand-icons.ts (${entries.map((i) => i.slug).join(', ')})`);
